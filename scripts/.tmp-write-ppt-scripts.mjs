if (PAGES.length !== 21) {
  throw new Error(`期望 21 页，实际 ${PAGES.length} 页`);
}

fs.mkdirSync(slidesDir, { recursive: true });

PAGES.forEach((utterance, index) => {
  const page = index + 1;
  const padded = String(page).padStart(2, '0');
  const content = [
    '---',
    'emotion: friendly',
    'gesture: explain',
    `action_id: ${deckId}-${padded}`,
    'slide_action: {"next": true}',
    '---',
    '',
    utterance,
    '',
  ].join('\n');
  fs.writeFileSync(path.join(slidesDir, `${padded}.md`), content, 'utf8');
});

console.log(`已写入 ${PAGES.length} 页讲稿 → ${slidesDir}`);
